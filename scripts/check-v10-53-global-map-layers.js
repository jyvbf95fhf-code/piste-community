'use strict';
const fs=require('fs');
const assert=require('assert');
const app=fs.readFileSync('app.js','utf8');
assert(fs.existsSync('map-base-layers.mjs'),'central base-layer catalog file missing');
const catalog=fs.readFileSync('map-base-layers.mjs','utf8');
assert(/export\s+const\s+BASE_LAYER_CATALOG/.test(catalog),'central base-layer catalog missing');
assert(/classic\s*:\s*Object\.freeze\(\{/.test(catalog)&&/topo\s*:\s*Object\.freeze\(\{/.test(catalog)&&/satellite\s*:\s*Object\.freeze\(\{/.test(catalog),'catalog must declare classic/topo/satellite');
assert(/export\s+function\s+normalizeBaseLayerId/.test(catalog),'base-layer id normalization missing');
assert(/fallbackId:'classic'/.test(catalog),'declared fallback must be classic');
assert(/productionAllowed:false/.test(catalog)&&/previewOnly:true/.test(catalog),'satellite must remain declared Preview-only');
assert(/from ['"]\.\/map-base-layers\.mjs['"]/.test(app),'app must import central base-layer catalog');
for(const method of ['getAvailableBaseLayers','getBaseLayer','setBaseLayer','fallbackBaseLayer','onBaseLayerChange'])assert(new RegExp(`\\b${method}\\s*\\(`).test(app),`PisteTerrainEngine.${method} contract missing`);
assert(/includeSatellite=false/.test(app),'satellite must remain opt-in per map');
assert(!/https:\/\/\{s\}\.tile\.openstreetmap\.org/.test(app),'OSM tile URL must not be duplicated in app.js');
assert(!/https:\/\/\{s\}\.tile\.opentopomap\.org/.test(app),'Topo tile URL must not be duplicated in app.js');
assert(/fallbackBaseLayer/.test(app),'deterministic base-layer fallback missing');
assert(/onBaseLayerChange/.test(app),'base-layer change subscription missing');
const setBaseLayer=app.slice(app.indexOf('setBaseLayer(id,name)'),app.indexOf('setBaseLayer(id,name)')+1200);
assert(!/replayPlayer|currentTime|replayDataset/.test(setBaseLayer),'base-layer switching must not mutate Replay state');
assert(/canonicalBaseLayerId\(normalized\)/.test(setBaseLayer),'base-layer UI callbacks must receive canonical ids');
assert(/map\.removeLayer\(current\)/.test(setBaseLayer),'base-layer switching must remove the previous layer');
assert(/replayPlayer/.test(app)&&/currentTime/.test(app),'Replay integration must remain present');
assert(!/maplibre-gl|maplibre\.js/i.test(app),'global map contract must not add a MapLibre dependency');
