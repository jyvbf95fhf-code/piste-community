'use strict';
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const assert=require('assert/strict');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const app=read('app.js');
const html=read('index.html');
const src=read('admin.js');
const css=read('admin.css');
const legacyGuard=read('scripts/check-v10-44.js');
const ok=(v,m)=>assert.ok(v,m);

for(const tab of ['dashboard','users','activity','statistics','feedback'])ok(src.includes(`${tab}:`),`Admin tab missing: ${tab}`);
ok(src.includes("piste_admin_access_v1044"),'Admin access RPC missing');
ok(src.includes("piste_admin_query_v1044"),'Admin query RPC missing');
ok(src.includes("piste_admin_feedback_status_v1044"),'Feedback status RPC missing');
ok(src.indexOf("piste_admin_access_v1044")<src.indexOf("piste_admin_query_v1044"),'Query must follow access check');
ok(!/client\.from\(/.test(src),'Admin must use protected RPCs, not direct table reads');
ok(!/localStorage|sessionStorage/.test(src),'Admin must not persist sensitive data locally');
ok(src.includes('catch(error)'),'Admin RPC errors must be handled');
ok(!/\$\{e\(u\.user_id\)\}/.test(src),'Raw user IDs must not be rendered in admin profile');
ok(/adminSearch|adminFilter|adminPeriod|adminSort/.test(src),'Admin filters/search missing');
ok(/overflow-x:auto/.test(css)&&/min-height:44px/.test(css)&&/minmax\(0,1fr\)/.test(css),'Admin mobile layout protections missing');
ok(/id="openAdminCentre"[^>]* hidden/.test(html),'Admin entry must be hidden before authorization');
ok(/if\(id==='adminPage'&&!adminVerified\)/.test(app),'Admin navigation must re-check authorization');
const ids=[...html.matchAll(/\bid="([^\"]+)"/g)].map(m=>m[1]);assert.equal(ids.length,new Set(ids).size,'Duplicate HTML IDs detected');
const context=vm.createContext({console,Date,Number,String,Object,Array,JSON});
vm.runInContext(src.replace(/export /g,''),context);
ok(src.includes("dashboard:'Tableau de bord',users:'Utilisateurs',activity:'Activité',statistics:'Statistiques',feedback:'Retours'"),'Admin tab contract mismatch');
const xss=context.adminUserCards([{user_id:'private',display_name:'<img src=x>',sessions_count:2}]);
ok(!xss.includes('<img'),'Admin output must escape user text');
const profile=context.renderAdmin('profile',{user:{user_id:'private-id',display_name:'Test',sessions_count:1}});
ok(!profile.includes('private-id'),'Profile must not expose raw user ID');
ok(context.renderAdmin('dashboard',{}).includes('Aucun utilisateur'),'Empty dashboard state missing');
ok(context.renderAdmin('activity',{}).includes('Aucun événement'),'Empty activity state missing');
ok(context.renderAdmin('feedback',{}).includes('Aucun retour'),'Empty feedback state missing');
console.log('v10.55 Admin guard: PASS');
